#!/usr/bin/env python3
"""Generate what the NetSurf build needs before compiling (the job of NetSurf's own make
rules, which need a Unix host): tables of the libraries, the framebuffer front end's images
and font, the testament, the JavaScript DOM bindings (nsgenbind) and the resources that go to
the SD card.

    python tools/netsurf_prepare.py GEN_DIR SD_SHARE_DIR

Sources: third_party/netsurf (the browser) and third_party/netsurf-libs (its libraries). Generated files that
the libraries include by relative path are written into their source trees (as their own
make rules do); the rest goes to GEN_DIR. Everything is regenerated only when older than
its inputs. Host tools: perl, gperf and a host C compiler (gcc, e.g. MinGW) on the PATH or
in the usual places; images need Python's PIL.
"""
import glob
import os
import re
import shutil
import socket
import subprocess
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
NS = os.path.join(ROOT, 'third_party', 'netsurf')
LIBS = os.path.join(ROOT, 'third_party', 'netsurf-libs')

_WINGET = os.path.join(os.environ.get('LOCALAPPDATA', ''), 'Microsoft', 'WinGet')
# where the host tools are when they are not on the PATH (Git for Windows has perl; winget
# installs gperf and WinLibs' MinGW gcc into its package directory)
HOST_TOOL_PLACES = {
    'perl': [r'C:\Program Files\Git\usr\bin', r'C:\Strawberry\perl\bin'],
    'gperf': [os.path.join(_WINGET, 'Links'), os.path.join(_WINGET, 'Packages', 'oss-winget.gperf_*')],
    'gcc': [r'C:\mingw64\bin', r'C:\msys64\ucrt64\bin', r'C:\msys64\mingw64\bin',
            os.path.join(_WINGET, 'Packages', 'BrechtSanders.WinLibs.*', 'mingw64', 'bin')],
}


def find_host_tool(name):
    """A program for the build computer: on the PATH or where its installer puts it"""
    p = shutil.which(name)
    if p:
        return p
    exe = name + ('.exe' if os.name == 'nt' else '')
    for pattern in HOST_TOOL_PLACES.get(name, []):
        for d in sorted(glob.glob(pattern), reverse=True):
            if os.path.isfile(os.path.join(d, exe)):
                return os.path.join(d, exe)
    return None


def tool(name):
    p = find_host_tool(name)
    if not p:
        sys.exit('netsurf_prepare: %s not found ("crtos setup --netsurf" installs it)' % name)
    return p


PERL = None
GPERF = None
HOSTCC = None


def stale(out, *inputs):
    if not os.path.exists(out):
        return True
    t = os.path.getmtime(out)
    return any(os.path.getmtime(i) > t for i in inputs)


def run(cmd, cwd=None, env=None):
    r = subprocess.run(cmd, cwd=cwd, env=env, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
    if r.returncode:
        sys.exit('netsurf_prepare: %s failed:\n%s' % (' '.join(cmd), r.stdout))
    return r.stdout


def write_if_changed(path, text):
    if os.path.exists(path) and open(path, encoding='utf-8', newline='').read() == text:
        return
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)


# ---- libraries ------------------------------------------------------------------------------

def libparserutils():
    lib = os.path.join(LIBS, 'libparserutils')
    out = os.path.join(lib, 'src', 'charset', 'aliases.inc')
    if stale(out, os.path.join(lib, 'build', 'Aliases'), os.path.join(lib, 'build', 'make-aliases.pl')):
        run([PERL, 'build/make-aliases.pl'], cwd=lib)


def libhubbub():
    lib = os.path.join(LIBS, 'libhubbub')
    out = os.path.join(lib, 'src', 'tokeniser', 'entities.inc')
    if stale(out, os.path.join(lib, 'build', 'Entities'), os.path.join(lib, 'build', 'make-entities.pl')):
        run([PERL, 'build/make-entities.pl'], cwd=lib)
    src = os.path.join(lib, 'src', 'treebuilder', 'element-type.gperf')
    out = os.path.join(lib, 'src', 'treebuilder', 'autogenerated-element-type.c')
    if stale(out, src):
        tmp = out + '.tmp'
        run([GPERF, '--output-file=' + tmp, src])
        text = open(tmp, encoding='utf-8').read()
        os.remove(tmp)
        text = re.sub(r'^(const struct element_type_map)', r'static \1', text, flags=re.M)
        write_if_changed(out, text)


def libsvgtiny():
    lib = os.path.join(LIBS, 'libsvgtiny')
    src = os.path.join(lib, 'src', 'colors.gperf')
    out = os.path.join(lib, 'src', 'autogenerated_colors.c')
    if stale(out, src):
        tmp = out + '.tmp'
        run([GPERF, '--output-file=' + tmp, src])
        text = open(tmp, encoding='utf-8').read()
        os.remove(tmp)
        text = re.sub(r'^(const struct svgtiny_named_color)', r'static \1', text, flags=re.M)
